using Niwahana_backend.Models.Domain;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Niwahana_backend.Services
{
    public class BungalowReportService
    {
        public byte[] GenerateBungalowReport(
            List<BungalowsMl> bungalows,
            string downloadedBy,
            DateTime generatedAt)
        {
            return Document.Create(document =>
            {
                document.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(30);
                    page.DefaultTextStyle(
                        style => style.FontSize(9));

                    page.Header().Column(column =>
                    {
                        column.Item().Text("NIWAHANA").FontSize(22).Bold().FontColor(Colors.Blue.Darken2);
                        column.Item().Text("Bungalow Management Report").FontSize(15).Bold();
                        column.Item().PaddingTop(8).Text($"Generated by: {downloadedBy}");
                        column.Item().Text($"Generated on: {generatedAt:yyyy-MM-dd HH:mm:ss}");
                        column.Item().Text($"Total bungalows: {bungalows.Count}");
                        column.Item().PaddingVertical(10).LineHorizontal(1).LineColor(Colors.Grey.Lighten1);
                    });

                    page.Content().Table(table =>
                    {
                        table.ColumnsDefinition(columns =>
                        {
                            columns.ConstantColumn(35);
                            columns.RelativeColumn(2);
                            columns.RelativeColumn(1);
                            columns.RelativeColumn(2);
                            columns.RelativeColumn(1);
                        });

                        table.Header(header =>
                        {
                            header.Cell().Element(HeaderCell).Text("ID");
                            header.Cell().Element(HeaderCell).Text("Name");
                            header.Cell().Element(HeaderCell).Text("Code");
                            header.Cell().Element(HeaderCell).Text("Location");
                            header.Cell().Element(HeaderCell).Text("Status");
                        });

                        foreach (var bungalow in bungalows)
                        {
                            table.Cell().Element(BodyCell).Text(bungalow.BungalowId.ToString());
                            table.Cell().Element(BodyCell).Text(bungalow.BungalowName);
                            table.Cell().Element(BodyCell).Text(bungalow.BungalowCode);
                            table.Cell().Element(BodyCell).Text(bungalow.BungalowLocation);
                            table.Cell().Element(BodyCell).Text(bungalow.IsActive ? "Active" : "Inactive");
                        }
                    });

                    page.Footer()
                        .AlignCenter()
                        .Text(text =>
                        {
                            text.Span("Niwahana | Bungalow Report | Page ");
                            text.CurrentPageNumber();
                            text.Span(" of ");
                            text.TotalPages();
                        });
                });
            }).GeneratePdf();
        }

        private static IContainer HeaderCell(IContainer container)
        {
            return container
                .Background(Colors.Blue.Darken2)
                .Border(1)
                .BorderColor(Colors.Grey.Lighten2)
                .Padding(5)
                .DefaultTextStyle(
                    style => style
                        .FontColor(Colors.White)
                        .Bold());
        }

        private static IContainer BodyCell(IContainer container)
        {
            return container
                .Border(1)
                .BorderColor(Colors.Grey.Lighten2)
                .Padding(5);
        }
    }
}
